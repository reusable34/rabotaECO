#!/bin/bash
# ==========================================
# ПРИНУДИТЕЛЬНЫЙ ПЕРЕСЧЕТ ТРЕБОВАНИЙ ДЛЯ ВСЕХ КЛИЕНТОВ
# ==========================================

PROJECT_DIR="/opt/eco-project"
BACKEND_DIR="$PROJECT_DIR/backend"

cd "$PROJECT_DIR" || exit 1

echo "=========================================="
echo "🔄 ПРИНУДИТЕЛЬНЫЙ ПЕРЕСЧЕТ ТРЕБОВАНИЙ ДЛЯ ВСЕХ КЛИЕНТОВ"
echo "=========================================="
echo ""
echo "⚠️ ВНИМАНИЕ: Все существующие требования будут удалены и созданы заново!"
echo ""
read -p "Продолжить? (yes/no): " confirm

if [ "$confirm" != "yes" ]; then
    echo "Отменено"
    exit 0
fi

cd "$BACKEND_DIR" || exit 1

echo ""
echo "Пересчет требований для всех клиентов..."
php yii recalculate-all/all

if [ $? -eq 0 ]; then
    echo ""
    echo "=========================================="
    echo "✅ ГОТОВО! Все требования пересчитаны"
    echo "=========================================="
else
    echo ""
    echo "❌ Ошибка при пересчете требований"
    exit 1
fi

