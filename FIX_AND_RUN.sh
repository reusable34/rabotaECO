#!/bin/bash
# ==========================================
# ИСПРАВЛЕНИЕ GIT И ЗАПУСК ВРУЧНУЮ
# ==========================================
# Выполните ВНУТРИ контейнера 102

set -e

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}=========================================="
echo "🔧 ИСПРАВЛЕНИЕ GIT И ЗАПУСК"
echo "==========================================${NC}"
echo ""

cd /opt/eco-project

# 1. Сохраняем локальные изменения
echo -e "${YELLOW}[1/3] Сохранение локальных изменений...${NC}"
git stash || echo -e "${YELLOW}⚠️ Нет изменений для сохранения${NC}"
echo ""

# 2. Обновляем проект
echo -e "${YELLOW}[2/3] Обновление проекта...${NC}"
git pull
echo -e "${GREEN}✅ Проект обновлен${NC}"
echo ""

# 3. Запуск контейнеров вручную
echo -e "${YELLOW}[3/3] Запуск контейнеров вручную...${NC}"
bash RUN_MANUAL.sh

